# простая функция чтоб в консоль красиво писать с временем
def log_message(message):
    # печатаю время в скобках и само сообщение
    print(f"[{time.strftime('%H:%M:%S')}] {message}")

# функция выбора города из выпадающего списка (работает и на главной и в корзине)
def select_city(page, city_name):
    # оборачиваю всё в трай, чтоб скрипт не падал если один город не выбрался
    try:
        # ищу кнопку которая открывает список городов, селекторов накидал несколько на случай если вёрстка поменяется
        city_button = page.locator(
            "button[class*='FirstLevelMenu_button__'], "  # класс кнопки в верхнем меню
            "button[class*='city'], "                     # альтернативный класс
            "button:has-text('Москва'), "                 # если в кнопке написано "Москва"
            "button:has-text('Абакан')"                   # если в кнопке написано "Абакан"
        ).first  # беру первую найденную из этого списка

        # прокручиваю страницу к кнопке чтоб точно видно было
        city_button.scroll_into_view_if_needed()
        # небольшая пауза, а то иногда клик не срабатывает
        page.wait_for_timeout(500)
        # кликаю чтоб модалка открылась
        city_button.click()
        # жду 2 сек пока модалка прогрузится
        page.wait_for_timeout(2000)

        # жду пока в модалке появятся кнопки городов (класс CitiesModal_cityName__W4Od4)
        page.wait_for_selector(".CitiesModal_cityName__W4Od4", timeout=8000)

        # беру все кнопки с городами
        buttons = page.locator(".CitiesModal_cityName__W4Od4").all()
        # прохожусь по каждой
        for button in buttons:
            # если текст кнопки (без пробелов по краям) точь-в-точь совпал с искомым
            if button.inner_text().strip() == city_name:
                # прокручиваю к этой кнопке
                button.scroll_into_view_if_needed()
                # пауза перед кликом
                page.wait_for_timeout(500)
                # кликаю по городу
                button.click()
                # жду 3 сек чтоб страница перезагрузила данные под выбранный город
                page.wait_for_timeout(3000)
                # верну тру, значит всё ок
                return True

        # если точного совпадения нет, пробую частичное (вдруг там пробелы лишние)
        for button in buttons:
            if city_name in button.inner_text():
                button.scroll_into_view_if_needed()
                page.wait_for_timeout(500)
                button.click()
                page.wait_for_timeout(3000)
                return True

        # если город так и не нашли, пишу в лог
        log_message(f"⚠️ Город {city_name} не найден в списке")
        # закрываю модалку ескейпом чтоб не мешала
        page.keyboard.press("Escape")
        # верну фолс
        return False

    # если произошла любая ошибка (элемент не найден или перекрыт)
    except Exception as e:
        # пишу ошибку в лог
        log_message(f"Ошибка при выборе города {city_name}: {e}")
        # пытаюсь закрыть модалку чтоб не сломать следующие шаги
        try:
            page.keyboard.press("Escape")
        except:
            pass
        # верну фолс
        return False

# функция добавления первых 7 чайников в корзину
def add_seven_kettles(page):
    # пишу что начал
    log_message("Добавление 7 чайников в корзину...")
    
    # пытаюсь дождаться загрузки карточек товаров (класс ProductLineCard)
    try:
        page.wait_for_selector("div[class*='ProductLineCard']", timeout=10000)
    # если за 10 сек не дождался
    except PlaywrightTimeoutError:
        # пишу ошибку
        log_message("❌ Товары не загрузились")
        # верну фолс
        return False

    # ищу все кнопки добавления в корзину внутри карточек
    add_buttons = page.locator("div[class*='ProductLineCard'] span[class*='basketText']").all()
    
    # если нашел меньше 7 кнопок (вдруг класс поменялся), ищу по тексту
    if len(add_buttons) < 7:
        add_buttons = page.locator("button:has-text('В корзину'), span:has-text('В корзину')").all()

    # счётчик сколько добавил
    count = 0
    # прохожусь по всем найденным кнопкам
    for btn in add_buttons:
        # если уже набрал 7, выхожу из цикла
        if count >= 7:
            break
        # пробую кликнуть
        try:
            # прокручиваю к кнопке
            btn.scroll_into_view_if_needed()
            # пауза
            page.wait_for_timeout(500)
            # кликаю
            btn.click()
            # плюсую счётчик
            count += 1
            # пишу что добавил
            log_message(f"  ✅ Добавлен товар {count}/7")
            # жду немного чтоб не долбить сервер частыми запросами
            page.wait_for_timeout(800)
        # если клик не удался
        except Exception as e:
            # пишу ошибку
            log_message(f"  ⚠️ Ошибка при клике на товар: {e}")
            # продолжаю цикл, пробую следующую кнопку
            continue

    # если в итоге добавил меньше 7
    if count < 7:
        # пишу предупреждение
        log_message(f"⚠️ Удалось добавить только {count} товаров")
        # верну фолс
        return False
        
    # если все 7 добавил, верну тру
    return True

# функция проверки наличия способов оплаты на текущей странице
def check_payments(page):
    # пытаюсь дождаться блока с оплатой (ищу текст 'Способ оплаты')
    try:
        page.wait_for_selector("text='Способ оплаты'", timeout=5000)
    # если не нашел (вдруг заголовок поменялся)
    except:
        # просто игнорирую, ниже всё равно по всему тексту искать буду
        pass 
    
    # даю странице 2 сек чтоб все радиокнопки и тексты отрисовались
    page.wait_for_timeout(2000)
    
    # беру весь видимый текст со страницы (включая скрытые элементы, мне это и надо)
    page_text = page.locator("body").inner_text()
    
    # пустой список для найденных способов
    found = []
    # прохожусь по каждому обязательному способу
    for payment in REQUIRED_PAYMENTS:
        # если название способа есть в тексте страницы
        if payment in page_text:
            # добавляю в найденные
            found.append(payment)
            
    # собираю список отсутствующих (тех которых нет в found)
    missing = [p for p in REQUIRED_PAYMENTS if p not in found]
    # возвращаю отсутствующие
    return missing

# главная функция которая всем рулит
def main():
    # запускаю плейрайт синхронно (через менеджер контекста)
    with sync_playwright() as p:
        # открываю хром
        browser = p.chromium.launch(
            headless=False,  # headless=False чтоб глазами видеть что происходит (удобно для отладки)
            # отключаю флаг автоматизации чтоб сайт не спалил бота
            args=["--disable-blink-features=AutomationControlled"],
        )
        # создаю контекст как будто инкогнито открыл
        context = browser.new_context(
            # подставляю юзер-агент обычного хрома
            user_agent=(
                "Mozilla/5.0 (Windows NT 10.0; Win64; x64) "
                "AppleWebKit/537.36 (KHTML, like Gecko) "
                "Chrome/120.0.0.0 Safari/537.36"
            ),
            # разрешение экрана 1920x1080 как у обычного пользователя
            viewport={"width": 1920, "height": 1080},
        )
        # новая страница в этом контексте
        page = context.new_page()
        # добавляю скрипт который выполняется до загрузки любой страницы
        # он прячет navigator.webdriver чтоб сайт не понял что это автоматизация
        page.add_init_script(
            "Object.defineProperty(navigator, 'webdriver', {get: () => undefined})"
        )

        # основной трай-эксепт-финалли чтоб ошибки ловить и браузер точно закрыть
        try:
            # пишу что стартую
            log_message("🚀 ЗАПУСК СКРИПТА")
            
            # 1. открываю главную страницу
            page.goto("https://www.leran.pro/", wait_until="domcontentloaded")
            # жду 3 сек чтоб страница прогрузилась
            page.wait_for_timeout(3000)
            
            # 2. выбираю город Абакан
            log_message("Выбор города Абакан...")
            # вызываю функцию выбора
            if not select_city(page, "Абакан"):
                # если не выбралось, выхожу
                log_message("❌ Не удалось выбрать Абакан. Выход.")
                return

            # 3. иду в категорию "Чайники электрические"
            log_message("Переход в категорию Чайники...")
            # открываю url категории
            page.goto("https://www.leran.pro/cat/kuhonnaya_tehnika/chainiki_elektricheskie/", wait_until="domcontentloaded")
            # жду 5 сек чтоб товары загрузились
            page.wait_for_timeout(5000)
            
            # 4. добавляю 7 товаров в корзину
            # если функция вернула фолс (не смогла добавить 7), завершаю скрипт
            if not add_seven_kettles(page):
                log_message("❌ Не удалось добавить 7 товаров. Выход.")
                return
                
            # 5. перехожу на страницу оформления заказа
            log_message("Переход на страницу оформления заказа...")
            # открываю корзину
            page.goto("https://www.leran.pro/basket/order/", wait_until="domcontentloaded")
            # жду 6 сек, страница оформления обычно тяжёлая
            page.wait_for_timeout(6000)

            # 6. начинаю цикл по всем городам
            log_message(f"Начало проверки городов (всего {len(ALL_CITIES)}).")
            
            # enumerate с 1 чтоб получить индекс и сам город
            for idx, city in enumerate(ALL_CITIES, 1):
                # пишу какой сейчас город и его номер
                log_message(f"\n--- {idx}/{len(ALL_CITIES)}: {city} ---")
                
                # первый город (Абакан) уже выбрал на шаге 2, для него переключать не надо
                if idx > 1:
                    # для остальных вызываю переключение
                    if not select_city(page, city):
                        # если не переключился, пишу в отчёт
                        report.append(f"{city} - не удалось переключить город")
                        # иду к следующему
                        continue
                
                # 7. проверяю наличие способов оплаты на странице
                missing = check_payments(page)
                
                # если список отсутствующих пуст
                if not missing:
                    # пишу что всё хорошо
                    log_message(f"  ✅ {city} - все {len(REQUIRED_PAYMENTS)} способов на месте")
                # если чего-то нет
                else:
                    # склеиваю отсутствующие через запятую
                    missing_str = ", ".join(missing)
                    # пишу чего не хватает
                    log_message(f"  ❌ {city} - ОТСУТСТВУЕТ: {missing_str}")
                    # добавляю в общий отчёт
                    report.append(f"{city} - отсутствует способ оплаты ({missing_str})")

            # 8. вывожу итоговый отчёт
            log_message("\n" + "=" * 60)  # разделитель для красоты
            log_message("📊 ИТОГОВЫЙ ОТЧЕТ ПО ОТСУТСТВУЮЩИМ СПОСОБАМ ОПЛАТЫ:")
            log_message("=" * 60)
            # если в отчёте что-то есть
            if report:
                # печатаю каждую строку
                for line in report:
                    log_message(f"  • {line}")
            # если пусто
            else:
                # значит везде всё на месте
                log_message("  Во всех городах присутствуют все способы оплаты!")
            # завершающая линия
            log_message("=" * 60)

        # если критическая ошибка (например браузер упал)
        except Exception as e:
            # пишу текст ошибки
            log_message(f"❌ КРИТИЧЕСКАЯ ОШИБКА: {e}")
            # печатаю полный стек для отладки
            traceback.print_exc()
        # финалли выполняется всегда, даже если была ошибка
        finally:
            # пишу что завершаюсь
            log_message("🛑 Завершение работы")
            # жду 3 сек перед закрытием чтоб успеть результат увидеть
            page.wait_for_timeout(3000)
            # закрываю контекст
            context.close()
            # закрываю браузер
            browser.close()

# точка входа: если скрипт запущен напрямую, вызываю main
if __name__ == "__main__":
    main()