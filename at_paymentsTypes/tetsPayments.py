# Вспомогательная функция для вывода сообщений в консоль с текущим временем
def log_message(message):
    # Выводим сообщение, предваряя его текущим временем в формате ЧЧ:ММ:СС
    print(f"[{time.strftime('%H:%M:%S')}] {message}")

# Функция выбора города из выпадающего списка (работает и на главной, и в корзине)
def select_city(page, city_name):
    # Оборачиваем все в try-except, чтобы скрипт не падал при ошибке выбора одного города
    try:
        # Ищем кнопку открытия списка городов. Используем несколько селекторов на случай изменения верстки
        city_button = page.locator(
            "button[class*='FirstLevelMenu_button__'], "  # Класс кнопки в верхнем меню
            "button[class*='city'], "                     # Альтернативный класс
            "button:has-text('Москва'), "                 # Если в кнопке написано "Москва"
            "button:has-text('Абакан')"                   # Если в кнопке написано "Абакан"
        ).first  # Берем первую найденную кнопку из списка селекторов

        # Прокручиваем страницу к кнопке, чтобы она точно была видна
        city_button.scroll_into_view_if_needed()
        # Небольшая пауза для стабильности
        page.wait_for_timeout(500)
        # Кликаем по кнопке, чтобы открыть модальное окно
        city_button.click()
        # Ждем 2 секунды, пока модальное окно прогрузится
        page.wait_for_timeout(2000)

        # Ждем, пока в модальном окне появятся кнопки с городами (класс CitiesModal_cityName__W4Od4)
        page.wait_for_selector(".CitiesModal_cityName__W4Od4", timeout=8000)

        # Находим все кнопки с названиями городов в модальном окне
        buttons = page.locator(".CitiesModal_cityName__W4Od4").all()
        # Проходимся по каждой кнопке
        for button in buttons:
            # Если текст кнопки (очищенный от пробелов) полностью совпадает с искомым городом
            if button.inner_text().strip() == city_name:
                # Прокручиваем к этой кнопке
                button.scroll_into_view_if_needed()
                # Пауза перед кликом
                page.wait_for_timeout(500)
                # Кликаем по городу
                button.click()
                # Ждем 3 секунды, чтобы страница перезагрузила данные для выбранного города
                page.wait_for_timeout(3000)
                # Возвращаем True, сигнализируя об успехе
                return True

        # Если точное совпадение не найдено, пробуем частичное совпадение (вдруг в названии есть лишние пробелы)
        for button in buttons:
            if city_name in button.inner_text():
                button.scroll_into_view_if_needed()
                page.wait_for_timeout(500)
                button.click()
                page.wait_for_timeout(3000)
                return True

        # Если город так и не нашли, пишем в лог
        log_message(f"⚠️ Город {city_name} не найден в списке")
        # Закрываем модальное окно нажатием Escape, чтобы оно не мешало
        page.keyboard.press("Escape")
        # Возвращаем False
        return False

    # Если произошла любая ошибка (например, элемент не найден или перекрыт)
    except Exception as e:
        # Логируем ошибку
        log_message(f"Ошибка при выборе города {city_name}: {e}")
        # Пытаемся закрыть модалку, чтобы не сломать следующие шаги
        try:
            page.keyboard.press("Escape")
        except:
            pass
        # Возвращаем False
        return False

# Функция добавления первых 7 чайников в корзину
def add_seven_kettles(page):
    # Логируем начало процесса
    log_message("Добавление 7 чайников в корзину...")
    
    # Пытаемся дождаться загрузки карточек товаров (класс ProductLineCard)
    try:
        page.wait_for_selector("div[class*='ProductLineCard']", timeout=10000)
    # Если не дождались за 10 секунд
    except PlaywrightTimeoutError:
        # Логируем ошибку
        log_message("❌ Товары не загрузились")
        # Возвращаем False
        return False

    # Ищем все кнопки добавления в корзину внутри карточек товаров
    add_buttons = page.locator("div[class*='ProductLineCard'] span[class*='basketText']").all()
    
    # Если нашли меньше 7 кнопок (вдруг класс изменился), ищем по тексту
    if len(add_buttons) < 7:
        add_buttons = page.locator("button:has-text('В корзину'), span:has-text('В корзину')").all()

    # Счетчик успешно добавленных товаров
    count = 0
    # Проходимся по всем найденным кнопкам
    for btn in add_buttons:
        # Если уже добавили 7 товаров, прерываем цикл
        if count >= 7:
            break
        # Пытаемся кликнуть по кнопке
        try:
            # Прокручиваем к кнопке
            btn.scroll_into_view_if_needed()
            # Пауза
            page.wait_for_timeout(500)
            # Кликаем
            btn.click()
            # Увеличиваем счетчик
            count += 1
            # Логируем успех
            log_message(f"  ✅ Добавлен товар {count}/7")
            # Ждем немного, чтобы не было слишком частых запросов к серверу
            page.wait_for_timeout(800)
        # Если клик не удался
        except Exception as e:
            # Логируем ошибку
            log_message(f"  ⚠️ Ошибка при клике на товар: {e}")
            # Продолжаем цикл (пробуем следующую кнопку)
            continue

    # Если в итоге добавили меньше 7 товаров
    if count < 7:
        # Логируем предупреждение
        log_message(f"⚠️ Удалось добавить только {count} товаров")
        # Возвращаем False
        return False
        
    # Если все 7 добавлены, возвращаем True
    return True

# Функция проверки наличия способов оплаты на текущей странице
def check_payments(page):
    # Пытаемся дождаться появления блока с оплатой (ищем текст 'Способ оплаты')
    try:
        page.wait_for_selector("text='Способ оплаты'", timeout=5000)
    # Если не нашли (например, изменился заголовок)
    except:
        # Просто игнорируем и продолжаем, так как ниже будем искать по всему тексту
        pass 
    
    # Даем странице 2 секунды на то, чтобы все радиокнопки и тексты отрисовались
    page.wait_for_timeout(2000)
    
    # Получаем весь видимый текст со страницы (включая скрытые элементы, что нам и нужно)
    page_text = page.locator("body").inner_text()
    
    # Создаем пустой список для найденных способов
    found = []
    # Проходимся по каждому обязательному способу оплаты
    for payment in REQUIRED_PAYMENTS:
        # Если название способа есть в тексте страницы
        if payment in page_text:
            # Добавляем его в список найденных
            found.append(payment)
            
    # Формируем список отсутствующих способов (те, которых нет в found)
    missing = [p for p in REQUIRED_PAYMENTS if p not in found]
    # Возвращаем список отсутствующих
    return missing

# Главная функция, которая управляет браузером и всем процессом
def main():
    # Запускаем Playwright в синхронном режиме (менеджер контекста)
    with sync_playwright() as p:
        # Запускаем браузер Chromium
        browser = p.chromium.launch(
            headless=False,  # headless=False означает, что мы видим окно браузера (удобно для отладки)
            # Отключаем флаг автоматизации, чтобы сайт не понял, что это бот
            args=["--disable-blink-features=AutomationControlled"],
        )
        # Создаем новый контекст (как будто открыли новое окно в режиме инкогнито)
        context = browser.new_context(
            # Подменяем User-Agent на обычный браузер Chrome
            user_agent=(
                "Mozilla/5.0 (Windows NT 10.0; Win64; x64) "
                "AppleWebKit/537.36 (KHTML, like Gecko) "
                "Chrome/120.0.0.0 Safari/537.36"
            ),
            # Устанавливаем разрешение экрана 1920x1080 (как у обычного пользователя)
            viewport={"width": 1920, "height": 1080},
        )
        # Создаем новую страницу в этом контексте
        page = context.new_page()
        # Добавляем скрипт, который будет выполняться до загрузки любой страницы
        # Он скрывает флаг navigator.webdriver, чтобы сайт не мог определить автоматизацию
        page.add_init_script(
            "Object.defineProperty(navigator, 'webdriver', {get: () => undefined})"
        )

        # Основной блок try-except-finally для обработки ошибок и корректного закрытия браузера
        try:
            # Логируем начало
            log_message("🚀 ЗАПУСК СКРИПТА")
            
            # 1. Открываем главную страницу сайта
            page.goto("https://www.leran.pro/", wait_until="domcontentloaded")
            # Ждем 3 секунды, чтобы страница полностью прогрузилась
            page.wait_for_timeout(3000)
            
            # 2. Выбираем город Абакан
            log_message("Выбор города Абакан...")
            # Вызываем функцию выбора города
            if not select_city(page, "Абакан"):
                # Если не удалось выбрать, выходим из скрипта
                log_message("❌ Не удалось выбрать Абакан. Выход.")
                return

            # 3. Переходим в категорию "Чайники электрические"
            log_message("Переход в категорию Чайники...")
            # Открываем URL категории
            page.goto("https://www.leran.pro/cat/kuhonnaya_tehnika/chainiki_elektricheskie/", wait_until="domcontentloaded")
            # Ждем 5 секунд, чтобы загрузились все товары
            page.wait_for_timeout(5000)
            
            # 4. Добавляем 7 товаров в корзину
            # Если функция вернула False (не удалось добавить 7), завершаем скрипт
            if not add_seven_kettles(page):
                log_message("❌ Не удалось добавить 7 товаров. Выход.")
                return
                
            # 5. Переходим на страницу оформления заказа
            log_message("Переход на страницу оформления заказа...")
            # Открываем страницу корзины
            page.goto("https://www.leran.pro/basket/order/", wait_until="domcontentloaded")
            # Ждем 6 секунд, так как страница оформления заказа часто содержит много скриптов
            page.wait_for_timeout(6000)

            # 6. Начинаем цикл по всем городам из списка
            log_message(f"Начало проверки городов (всего {len(ALL_CITIES)}).")
            
            # enumerate с 1 позволяет нам получить индекс (idx) и сам город (city)
            for idx, city in enumerate(ALL_CITIES, 1):
                # Логируем текущий город и его номер
                log_message(f"\n--- {idx}/{len(ALL_CITIES)}: {city} ---")
                
                # Первый город (Абакан) мы уже выбрали на шаге 2, поэтому для него переключение не нужно
                if idx > 1:
                    # Для всех остальных вызываем функцию переключения
                    if not select_city(page, city):
                        # Если не удалось переключить, записываем это в отчет
                        report.append(f"{city} - не удалось переключить город")
                        # Переходим к следующему городу
                        continue
                
                # 7. Проверяем наличие способов оплаты на текущей странице
                missing = check_payments(page)
                
                # Если список отсутствующих пуст
                if not missing:
                    # Логируем, что все хорошо
                    log_message(f"  ✅ {city} - все {len(REQUIRED_PAYMENTS)} способов на месте")
                # Если чего-то не хватает
                else:
                    # Объединяем отсутствующие способы в строку через запятую
                    missing_str = ", ".join(missing)
                    # Логируем, чего именно не хватает
                    log_message(f"  ❌ {city} - ОТСУТСТВУЕТ: {missing_str}")
                    # Добавляем запись в глобальный отчет
                    report.append(f"{city} - отсутствует способ оплаты ({missing_str})")

            # 8. Выводим итоговый отчет в консоль
            log_message("\n" + "=" * 60)  # Разделитель для красоты
            log_message("📊 ИТОГОВЫЙ ОТЧЕТ ПО ОТСУТСТВУЮЩИМ СПОСОБАМ ОПЛАТЫ:")
            log_message("=" * 60)
            # Если в отчете есть записи
            if report:
                # Печатаем каждую строку
                for line in report:
                    log_message(f"  • {line}")
            # Если отчет пуст
            else:
                # Значит, везде все способы оплаты есть
                log_message("  Во всех городах присутствуют все способы оплаты!")
            # Завершающая линия
            log_message("=" * 60)

        # Если в процессе выполнения произошла критическая ошибка (например, упал браузер)
        except Exception as e:
            # Логируем текст ошибки
            log_message(f"❌ КРИТИЧЕСКАЯ ОШИБКА: {e}")
            # Печатаем полный стек ошибки для отладки
            traceback.print_exc()
        # Блок finally выполняется всегда, даже если была ошибка
        finally:
            # Логируем завершение
            log_message("🛑 Завершение работы")
            # Ждем 3 секунды перед закрытием, чтобы вы успели увидеть результат
            page.wait_for_timeout(3000)
            # Закрываем контекст браузера
            context.close()
            # Закрываем сам браузер
            browser.close()

# Точка входа в программу: если скрипт запущен напрямую, вызываем main()
if __name__ == "__main__":
    main()